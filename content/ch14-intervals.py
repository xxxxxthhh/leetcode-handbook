TPL_A = '''\
def merge_intervals(intervals):
    intervals.sort()                        # 【骨架】按起点排序 —— 区间题的第一行
    out = []
    for s, e in intervals:                  # 【骨架】
        if out and s <= out[-1][1]:         # 【插槽】重叠判定:<= 表示"碰到端点也算重叠"
            out[-1][1] = max(out[-1][1], e) # 【插槽】重叠了怎么办:合并 / 计数 / 丢一个
        else:
            out.append([s, e])              # 【骨架】不重叠就新开一段
    return out
'''

TPL_A_TESTS = '''\
assert merge_intervals([[1, 3], [2, 6], [8, 10], [15, 18]]) == [[1, 6], [8, 10], [15, 18]]
assert merge_intervals([[1, 4], [4, 5]]) == [[1, 5]]        # 端点相碰:本题算重叠
assert merge_intervals([[1, 4], [2, 3]]) == [[1, 4]]        # 完全被包含
assert merge_intervals([]) == []


# 435 Non-overlapping Intervals:改按**终点**排序,贪心留下结束最早的
def erase_overlap_intervals(intervals):
    if not intervals:
        return 0
    intervals.sort(key=lambda x: x[1])
    kept, last_end = 1, intervals[0][1]
    for s, e in intervals[1:]:
        if s >= last_end:                   # 端点相碰不算重叠,可以接着排
            kept += 1
            last_end = e
    return len(intervals) - kept


assert erase_overlap_intervals([[1, 2], [2, 3], [3, 4], [1, 3]]) == 1
assert erase_overlap_intervals([[1, 2], [1, 2], [1, 2]]) == 2
assert erase_overlap_intervals([[1, 2], [2, 3]]) == 0
'''

TPL_B = '''\
def min_meeting_rooms(intervals):
    starts = sorted(x[0] for x in intervals)      # 【骨架】起点和终点拆开各自排序
    ends = sorted(x[1] for x in intervals)
    rooms = best = j = 0
    for s in starts:                              # 【骨架】按时间推进,每来一个开始
        while j < len(ends) and ends[j] <= s:     # 【插槽】<= 表示"上一场刚结束就能接下一场"
            j += 1                                # 【骨架】先把已结束的房间腾出来
            rooms -= 1
        rooms += 1                                # 【骨架】占一间
        best = max(best, rooms)                   # 【插槽】答案:峰值 / 每一刻的值
    return best
'''

TPL_B_TESTS = '''\
assert min_meeting_rooms([[0, 30], [5, 10], [15, 20]]) == 2
assert min_meeting_rooms([[7, 10], [2, 4]]) == 1
assert min_meeting_rooms([[1, 5], [2, 6], [3, 7]]) == 3
assert min_meeting_rooms([[1, 2], [2, 3], [3, 4]]) == 1   # 首尾相接不算冲突
'''

